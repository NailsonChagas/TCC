// Esta função é chamada automaticamente pelo hardware assim que o ADC termina de 
// converter o sinal trigado pelo Timer 1. Custo de espera = 0 ciclos.
void HAL_ADCEx_InjectedConvCpltCallback(ADC_HandleTypeDef *hadc) {
  if (hadc->Instance == ADC1) {
    /* 1. LEITURA IMEDIATA DO ADC */
    // Pega o valor já convertido do registrador de injeção (Rank 1)
    uint32_t adc_raw = HAL_ADCEx_InjectedGetValue(&hadc1, ADC_INJECTED_RANK_1);

    float IN = (float)adc_raw * 0.0122100122f;

    /* 2. GERAÇÃO DO DEGRAU DE TEMPO */
    t_ticks++;
    if (t_ticks >= TICKS_PARA_DEGRAU) {
      Vref = VREF_INICIAL + VREF_INCREMENTO;
    } else {
      Vref = VREF_INICIAL;
    }

    /* 3. CÁLCULO DO ERRO E LEI DE CONTROLE PI */
    float E = Vref - IN;

    float U = pastU + 0.000357719f * E + 0.000346881f * pastE;

    /* 4. SATURAÇÃO DO SINAL DE CONTROLE */
    if (U > 1.0f)
      U = 1.0f;
    else if (U < 0.0f)
      U = 0.0f;

    /* 5. ATUALIZAÇÃO DOS ESTADOS */
    pastE = E;
    pastU = U;

    /* 6. SAÍDA PARA O PWM EM HARDWARE */
    TIM1->CCR1 = (uint32_t)(U * 1440.0f);
  }
}
